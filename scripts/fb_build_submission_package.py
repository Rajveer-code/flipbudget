"""Assembles SUBMISSION_FINAL/ -- a clean, self-contained package of the
rebuilt paper (PLAN_REBUILD.md) that rebuilds without this repo's history or
any local paths. Deterministic; copies only, the repo is untouched.

Run: python scripts/fb_build_submission_package.py
"""
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "SUBMISSION_FINAL"
FIGURES = ["figA_per_model_intervals.png", "figB_audit_sizing.png", "figC_differential_error.png",
           "figD_design_comparison.png", "figE_homogeneity_sensitivity.png"]
EVIDENCE = ["CLAIM_LEDGER.md", "CORE_ESTIMAND_AUDIT.md", "FINAL_STATUS.md",
            "REAUDIT.md", "STRESS_TEST.md", "results/flipbudget/rebuild_results.json", "results/flipbudget/core_estimand_audit.json",
            "results/flipbudget/joint_verifier_results.json", "results/flipbudget/reaudit_results.json",
            "results/flipbudget/reproducibility_run_2026-09-19.log"]


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    pdf_src = ROOT / "manuscript/latex/main.pdf"
    if not pdf_src.exists():
        sys.exit("STOPPED: compile manuscript/latex/main.pdf first.")
    shutil.copy(pdf_src, OUT / "paper.pdf")

    latex_out = OUT / "latex_source"
    shutil.copytree(ROOT / "manuscript/latex", latex_out, ignore=shutil.ignore_patterns(
        "*.aux", "*.log", "*.out", "*.bbl", "*.blg", "main.pdf", "references_pre_rebuild.bib"))
    (latex_out / "figures").mkdir()
    (OUT / "figures").mkdir()
    for f in FIGURES:
        shutil.copy(ROOT / "figures" / f, latex_out / "figures" / f)
        shutil.copy(ROOT / "figures" / f, OUT / "figures" / f)
    main_tex = latex_out / "main.tex"
    main_tex.write_text(main_tex.read_text(encoding="utf-8").replace(
        r"\graphicspath{{../../figures/}}", r"\graphicspath{{figures/}}"), encoding="utf-8")

    (OUT / "evidence").mkdir()
    for f in EVIDENCE:
        src = ROOT / f
        if not src.exists():
            sys.exit(f"STOPPED: missing evidence file {f}")
        shutil.copy(src, OUT / "evidence" / src.name)

    shutil.copy(ROOT / "LICENSE", OUT / "LICENSE")
    shutil.copy(ROOT / "CITATION.cff", OUT / "CITATION.cff")

    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    (OUT / "README.md").write_text(f"""# Submission package -- Audit the Disagreements

Built from code-repository commit `{commit}`.

- `paper.pdf` -- compiled manuscript.
- `latex_source/` -- self-contained source (`pdflatex`, `bibtex`, `pdflatex` x2).
  `numbers.tex`, `tab_models.tex`, `tab_sim.tex` are generated by
  `scripts/fb_rebuild_numbers.py`; do not edit by hand.
- `figures/` -- the three figures, generated by `scripts/fb_rebuild_figures.py`.
- `evidence/` -- claim ledger, the core estimand audit, status, result JSONs,
  and the full reproducibility log.

Reproduce from the code repository: `pip install -e ".[dev]"`, `pytest tests/`,
`python scripts/fb_reproduce_all.py`. All data (public Open LLM Leaderboard v2
MATH-Hard generations and the committed human audit) are in the repository;
no personal or restricted data are included.
""", encoding="utf-8")

    bad = [str(p.relative_to(OUT)) for p in OUT.rglob("*")
           if p.is_file() and p.suffix in {".md", ".tex", ".bib", ".json", ".log"}
           and any(s in p.read_text(encoding="utf-8", errors="ignore")
                   for s in ("C:\\Users\\", "C:/Users/", "D:\\Projects\\", "D:/Projects/"))]
    if bad:
        sys.exit("STOPPED: personal machine paths in: " + ", ".join(bad))
    print(f"Built {OUT}: {sum(1 for p in OUT.rglob('*') if p.is_file())} files, no personal paths.")


if __name__ == "__main__":
    main()
