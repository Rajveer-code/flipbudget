"""Generate the manuscript's tables from committed results. No number is typed here.

Run: python scripts/fb_tables_tmlr.py    Out: manuscript/tmlr/tables.tex
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results" / "flipbudget"
OUT = ROOT / "manuscript" / "tmlr" / "tables.tex"
NAMES = {"111": "all three credit", "000": "none credits"}


def thousands(n):
    return f"{n:,}".replace(",", "{,}")


def main():
    cert = json.load(open(RES / "certify_results.json", encoding="utf-8"))
    amap = json.load(open(RES / "audit_k3_map.json", encoding="utf-8"))
    cfg = json.load(open(RES / "verifier_config.json", encoding="utf-8"))
    cells = amap["census_cells"]["k3_sympy"]["27"]
    audit = amap["audit_cells"]["27|k3_sympy|sympy|as_incorrect"]
    rows = []
    for c in sorted(cells, key=lambda c: -cells[c]):
        a = audit.get(c)
        lab = NAMES.get(c, "verifiers disagree")
        got = f"{a['x_correct']}/{a['n']}" if a and a["n"] else "--"
        rows.append(f"{c} & {lab} & {thousands(cells[c])} & {got} \\\\")
    v = cfg["verifiers"]
    shared = [
        ("answer extraction", "sentence pattern", "last boxed expression", "LaTeX and expression parse"),
        ("normalisation", "harness routine", "harness routine", "latex2sympy2"),
        ("equivalence", "sympy", "string, then sympy", "Math-Verify"),
        ("reference answer", "dataset field", "dataset field", "parsed from the solution"),
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("% Generated by scripts/fb_tables_tmlr.py -- do not edit by hand.\n")
        f.write("\\begin{table}[t]\n\\centering\n\\caption{Verifier cells on MATH-Hard. A cell is the "
                "string of verdicts of the three verifiers, in the order (leaderboard 2024, boxed, "
                "Math-Verify). The last column is the share of audited responses in that cell that the "
                "human reference credits.}\n\\label{tab:cells}\n")
        f.write("\\begin{tabular}{llrr}\n\\toprule\ncell & reading & responses & human credits \\\\\n\\midrule\n")
        f.write("\n".join(rows))
        f.write("\n\\bottomrule\n\\end{tabular}\n\\end{table}\n\n")
        f.write("\\begin{table}[t]\n\\centering\n\\caption{What the three verifiers share. They are not "
                "independent; agreement between them is informative only because their extraction rules "
                "and parsers differ.}\n\\label{tab:shared}\n")
        f.write("\\begin{tabular}{llll}\n\\toprule\ncomponent & leaderboard 2024 & boxed & Math-Verify \\\\\n"
                "\\midrule\n")
        for r in shared:
            f.write(" & ".join(r) + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    print("wrote", OUT, "| cells:", len(rows), "| verifier keys:", list(v))


if __name__ == "__main__":
    main()
