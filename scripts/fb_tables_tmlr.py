"""Generate the manuscript's tables from committed results. No number is typed here.

Run: python scripts/fb_tables_tmlr.py    Out: manuscript/tmlr/tables.tex
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results" / "flipbudget"
OUT = ROOT / "manuscript" / "tmlr" / "tables.tex"
SENS_OUT = ROOT / "manuscript" / "tmlr" / "sensitivity_table.tex"
NAMES = {"111": "all three credit", "000": "none credits"}
# (key in certify_results K3.sensitivity, row label, what the row changes relative to the primary)
SENS_ROWS = [
    ("clopper_pearson", "Clopper--Pearson interval", "pooled interval, in place of Lemma~\\ref{lem:kl}"),
    ("mv_reference", "Math-Verify reference", "routine deciding $Y^*$"),
    ("indeterminate_dropped", "indeterminates dropped", "\\textsc{none} and \\textsc{contradictory} excluded"),
    ("string_semantics", "string semantics", "boxed verifier \\emph{and} reference routine"),
    ("models17", "earlier model subset", "models, and therefore the family size"),
]


def thousands(n):
    return f"{n:,}".replace(",", "{,}")


def main():
    cert = json.load(open(RES / "certify_results.json", encoding="utf-8"))
    amap = json.load(open(RES / "audit_k3_map.json", encoding="utf-8"))
    cfg = json.load(open(RES / "verifier_config.json", encoding="utf-8"))
    cells = amap["census_cells"]["k3_sympy"]["27"]
    audit = amap["audit_cells"]["27|k3_sympy|sympy|as_incorrect"]
    rows = []
    for c in sorted(cells, key=lambda c: -cells[c]):
        a = audit.get(c)
        lab = NAMES.get(c, "verifiers disagree")
        got = f"{a['x_correct']}/{a['n']}" if a and a["n"] else "--"
        rows.append(f"{c} & {lab} & {thousands(cells[c])} & {got} \\\\")
    v = cfg["verifiers"]
    shared = [
        ("answer extraction", "sentence pattern", "last boxed expression", "LaTeX and expression parse"),
        ("normalisation", "harness routine", "harness routine", "latex2sympy2"),
        ("equivalence", "sympy", "string, then sympy", "Math-Verify"),
        ("reference answer", "dataset field", "dataset field", "parsed from the solution"),
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("% Generated by scripts/fb_tables_tmlr.py -- do not edit by hand.\n")
        f.write("\\begin{table}[t]\n\\centering\n\\caption{Verifier cells on MATH-Hard. A cell is the "
                "string of verdicts of the three verifiers, in the order (leaderboard 2024, boxed, "
                "Math-Verify). The last column is the share of audited responses in that cell that the "
                "human reference credits.}\n\\label{tab:cells}\n")
        f.write("\\begin{tabular}{llrr}\n\\toprule\ncell & reading & responses & human credits \\\\\n\\midrule\n")
        f.write("\n".join(rows))
        f.write("\n\\bottomrule\n\\end{tabular}\n\\end{table}\n\n")
        f.write("\\begin{table}[t]\n\\centering\n\\caption{What the three verifiers share. They are not "
                "independent; agreement between them is informative only because their extraction rules "
                "and parsers differ.}\n\\label{tab:shared}\n")
        f.write("\\begin{tabular}{llll}\n\\toprule\ncomponent & leaderboard 2024 & boxed & Math-Verify \\\\\n"
                "\\midrule\n")
        for r in shared:
            f.write(" & ".join(r) + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table}\n")

    k3, sens = cert["K3"], cert["K3"]["sensitivity"]
    eps0 = cert["config"]["eps0_preregistered"]

    def pooled(d, cell):
        a = d.get(cell)
        return f"{a['x_correct']}/{a['n']}" if a and a["n"] else "--"

    def curve(eps):
        return next(r for r in k3["eps_curve"] if r["eps"] == eps)

    srows = ["registered primary & -- & {} & {} & {} & {} & {} \\\\".format(
        pooled(k3["inputs"]["audit_pooled"], "111"), pooled(k3["inputs"]["audit_pooled"], "000"),
        curve(0.0)["audit_only"], curve(0.0)["combined"], curve(eps0)["combined"])]
    for key, label, changed in SENS_ROWS:
        s = sens[key]
        srows.append("{} & {} & {} & {} & {} & {} & {} \\\\".format(
            label, changed, pooled(s["audit_pooled"], "111"), pooled(s["audit_pooled"], "000"),
            s["audit_only"], s["combined_eps0"][0], s["combined_eps0"][1]))
    with open(SENS_OUT, "w", encoding="utf-8") as f:
        f.write("% Generated by scripts/fb_tables_tmlr.py -- do not edit by hand.\n")
        f.write("\\begin{table}[t]\n\\centering\n\\caption{Registered sensitivity analyses. Each row "
                "re-runs the whole pipeline with one element of the analysis replaced, and reports the "
                "pooled audit counts it produces in the two concordant cells together with the certified "
                "orderings. The last row uses a different set of models, so its counts are out of a "
                "smaller family and are not comparable to the rest of the column.}\n"
                "\\label{tab:sensitivity}\n\\small\n")
        f.write("\\begin{tabular}{llccrrr}\n\\toprule\n"
                "analysis & what changes & $111$ & $000$ & audit-only & "
                "$\\varepsilon=0$ & $\\varepsilon=\\EpsPrereg$ \\\\\n\\midrule\n")
        f.write("\n".join(srows))
        f.write("\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")
    print("wrote", OUT, "| cells:", len(rows), "| verifier keys:", list(v))
    print("wrote", SENS_OUT, "|", len(srows), "sensitivity rows")


if __name__ == "__main__":
    main()
